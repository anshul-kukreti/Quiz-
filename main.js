const questionText = document.querySelector(".question-text");
const answerButtons = document.querySelectorAll(".answer-btn");
const nextBtn = document.querySelector(".next-btn");

const scoreDisplay = document.querySelector(".score");
const counterDisplay = document.querySelector(".question-counter");
const progressFill = document.querySelector(".progress-fill");

const quizContainer = document.querySelector(".quiz-container");
const resultContainer = document.querySelector(".result-container");

const finalScore = document.querySelector(".final-score");
const restartBtn = document.querySelector(".restart-btn");

let quizQuestions = [];
let currentQuestionIndex = 0;

let score = 0;
let correctCount = 0;
let wrongCount = 0;

let highestScore = Number(localStorage.getItem("highestScore")) || 0;

function shuffleArray(array) {

    for (let i = array.length - 1; i > 0; i--) {

        const randomIndex = Math.floor(Math.random() * (i + 1));

        [array[i], array[randomIndex]] = [array[randomIndex], array[i]];
    }
}

function startQuiz() {

    quizQuestions = [...questions];

    shuffleArray(quizQuestions);

    quizQuestions = quizQuestions.slice(0, 10);

    quizQuestions.forEach((q) => {
        q.options = [...q.options];
        shuffleArray(q.options);
    });

    currentQuestionIndex = 0;
    score = 0;
    correctCount = 0;
    wrongCount = 0;

    scoreDisplay.textContent = "Score: 0";

    resultContainer.style.display = "none";
    quizContainer.style.display = "block";

    showQuestion();
}

function showQuestion() {

    const currentQuestion = quizQuestions[currentQuestionIndex];

    questionText.textContent = currentQuestion.question;

    answerButtons.forEach((button, index) => {

        button.textContent = currentQuestion.options[index];

        button.classList.remove("correct", "wrong");

        button.disabled = false;
    });

    counterDisplay.textContent =
        `Question ${currentQuestionIndex + 1} / ${quizQuestions.length}`;

    const progress =
        ((currentQuestionIndex + 1) / quizQuestions.length) * 100;

    progressFill.style.width = `${progress}%`;

    nextBtn.style.display = "none";
}

function checkAnswer(selectedIndex) {

    const currentQuestion = quizQuestions[currentQuestionIndex];

    answerButtons.forEach((button) => {
        button.disabled = true;
    });

    const selectedText = answerButtons[selectedIndex].textContent;

    if (selectedText === currentQuestion.correctAnswer) {

        answerButtons[selectedIndex].classList.add("correct");

        score++;
        correctCount++;

        scoreDisplay.textContent = `Score: ${score}`;

    } else {

        answerButtons[selectedIndex].classList.add("wrong");

        answerButtons.forEach((button) => {
            if (button.textContent === currentQuestion.correctAnswer) {
                button.classList.add("correct");
            }
        });

        wrongCount++;
    }

    nextBtn.style.display = "block";
}

function nextQuestion() {

    currentQuestionIndex++;

    if (currentQuestionIndex < quizQuestions.length) {

        showQuestion();

    } else {

        showResult();
    }
}

function showResult() {

    const totalQuestions = quizQuestions.length;

    const percentage = Math.round((correctCount / totalQuestions) * 100);

    if (score > highestScore) {

        highestScore = score;

        localStorage.setItem("highestScore", highestScore);
    }

    quizContainer.style.display = "none";
    resultContainer.style.display = "block";

    finalScore.innerHTML = `
        Score: ${score} / ${totalQuestions}<br>
        Correct: ${correctCount} ✅<br>
        Wrong: ${wrongCount} ❌<br>
        Percentage: ${percentage}%<br>
        Highest Score: ${highestScore}
    `;
}

answerButtons.forEach((button, index) => {

    button.addEventListener("click", () => {
        checkAnswer(index);
    });

});

nextBtn.addEventListener("click", () => {
    nextQuestion();
});

restartBtn.addEventListener("click", () => {
    startQuiz();
});

startQuiz();